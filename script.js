const supportedLanguages = ['de', 'en', 'ru'];
const savedLanguage = localStorage.getItem('darky-language');
const browserLanguage = (navigator.language || 'en').toLowerCase().split('-')[0];
let currentLanguage = supportedLanguages.includes(savedLanguage)
  ? savedLanguage
  : (supportedLanguages.includes(browserLanguage) ? browserLanguage : 'en');

function t(key) {
  return translations[currentLanguage]?.[key] ?? translations.en[key] ?? key;
}

function applyLanguage(language) {
  if (!supportedLanguages.includes(language)) return;
  currentLanguage = language;
  localStorage.setItem('darky-language', language);
  document.documentElement.lang = language;

  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const key = element.dataset.i18n;
    if (translations[language][key] !== undefined) {
      element.textContent = translations[language][key];
    }
  });

  document.querySelectorAll('[data-i18n-html]').forEach((element) => {
    const key = element.dataset.i18nHtml;
    if (translations[language][key] !== undefined) {
      element.innerHTML = translations[language][key];
    }
  });

  document.querySelectorAll('.lang-btn').forEach((button) => {
    const active = button.dataset.lang === language;
    button.classList.toggle('active', active);
    button.setAttribute('aria-pressed', String(active));
  });
}

document.querySelectorAll('.lang-btn').forEach((button) => {
  button.addEventListener('click', () => applyLanguage(button.dataset.lang));
});

applyLanguage(currentLanguage);

const reducedMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches;

// Tiny animated night sky
const starField = document.querySelector('.star-field');
if (starField && !reducedMotion) {
  for (let i = 0; i < 70; i += 1) {
    const star = document.createElement('span');
    star.style.left = `${Math.random() * 100}%`;
    star.style.top = `${Math.random() * 100}%`;
    star.style.setProperty('--dur', `${1.8 + Math.random() * 3.8}s`);
    star.style.animationDelay = `${Math.random() * 4}s`;
    const size = Math.random() > 0.85 ? 3 : 2;
    star.style.width = `${size}px`;
    star.style.height = `${size}px`;
    starField.appendChild(star);
  }
}

// Reveal sections as you scroll
const reveals = document.querySelectorAll('.reveal');
if ('IntersectionObserver' in window && !reducedMotion) {
  const observer = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (!entry.isIntersecting) return;
      const delay = Number(entry.target.dataset.delay || 0);
      window.setTimeout(() => entry.target.classList.add('visible'), delay);
      observer.unobserve(entry.target);
    });
  }, { threshold: 0.12 });

  reveals.forEach((el) => observer.observe(el));
} else {
  reveals.forEach((el) => el.classList.add('visible'));
}

